// Optional release-maintenance tool. Run cargo metadata for the Windows target first.
// No network requests; all text comes from the lock-resolved, downloaded crate sources.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const input = readFileSync(process.argv[2] ?? '.local/windows-metadata.json');
const metadata = JSON.parse(input.toString(input[0] === 0xff ? 'utf16le' : 'utf8').replace(/^\uFEFF/, ''));
const packages = metadata.packages.filter(p => p.source).sort((a,b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`));
const apachePackage = packages.find(p => p.name === 'glutin');
if (!apachePackage) throw new Error('Windows dependency metadata is required');
const apache = readFileSync(join(dirname(apachePackage.manifest_path), 'LICENSE'), 'utf8');
let output = `# Third-party notices and attribution

Zoomer is independently implemented and inspired by [tsoding/boomer](https://github.com/tsoding/boomer).
It is not an official Boomer port. No Boomer source or assets were copied.
The magnifying glass icon is original procedural geometry.

Project license: owner decision TODO; no license has been assigned to Zoomer.

The following ${packages.length} registry packages are the Windows-target dependency
graph from Cargo.lock, including build tools. Text is copied from the downloaded
crates' license, notice and copyright files. OR expressions offer alternative
licenses; AND expressions retain their additional notices. Source libraries
remain under their upstream terms. Rust and Windows/OpenGL system components
are used as provided by their vendors. This inventory is generated by
scripts/collect-notices.mjs from cargo metadata for x86_64-pc-windows-msvc.

`;
for (const pkg of packages) {
  const root = dirname(pkg.manifest_path);
  const files = readdirSync(root).filter(n => /^(licen[sc]e|copying|copyright|notice)/i.test(n) && statSync(join(root,n)).isFile());
  output += `## ${pkg.name} ${pkg.version}\n\nLicense expression: ${pkg.license}\n\nSource: https://crates.io/crates/${pkg.name}/${pkg.version}\n\n`;
  if (!files.length) {
    if (!['gl_generator','khronos_api'].includes(pkg.name)) throw new Error(`No license text for ${pkg.name}`);
    const sourceFile = pkg.name === 'gl_generator' ? 'lib.rs' : 'src/lib.rs';
    const header = readFileSync(join(root,sourceFile),'utf8').split(/\r?\n/).slice(0,14).join('\n');
    output += `Upstream source header (the crate omits a standalone license file):\n\n\`\`\`text\n${header}\n\`\`\`\n\nApache-2.0 license text (identical standard license from glutin):\n\n\`\`\`text\n${apache}\n\`\`\`\n\n`;
    if (pkg.name === 'khronos_api') {
      for (const file of ['api/xml/wgl.xml','api/xml/gl.xml','api/xml/glx.xml','api_egl/api/egl.xml']) {
        const xml = readFileSync(join(root,file),'utf8');
        const notice = xml.match(/<comment>[\s\S]*?<\/comment>/)?.[0] ?? xml.match(/<!--[\s\S]*?Copyright[\s\S]*?-->/)?.[0];
        if (!notice) throw new Error(`Registry notice absent from ${file}`);
        output += `Registry copyright notice (${file}):\n\n\`\`\`text\n${notice}\n\`\`\`\n\n`;
      }
    }
  }
  for (const file of files.sort()) {
    output += `### ${file}\n\n\`\`\`text\n${readFileSync(join(root,file),'utf8').trim()}\n\`\`\`\n\n`;
  }
}
writeFileSync(resolve('THIRD_PARTY_NOTICES.md'), output, 'utf8');
console.log(`Collected notices for ${packages.length} Windows registry dependencies (${Buffer.byteLength(output)} bytes)`);
